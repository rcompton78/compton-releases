#!/usr/bin/env bash
#
# Installs the newest release of a tool from rcompton78/compton-releases.
# Linux x86_64 only: each release is a static musl binary.
#
#   curl -fsSL https://raw.githubusercontent.com/rcompton78/compton-releases/main/install.sh | bash -s <project>
#
# or run a release's install.sh, which has its app as the default. It lists the repo's releases,
# picks the newest non-draft, non-prerelease <project>@<version> with its tarball and .sha256,
# checks the sha256 and the new binary's --version, and installs it into $INSTALL_DIR (default
# ~/.local/bin). <bin> defaults to <project>. A failed download pipes nothing to bash, which exits
# 0, so check for the final "Installed" line.
#
# No token is needed. One in <PROJECT>_GH_TOKEN, GH_TOKEN, GITHUB_TOKEN or `gh auth token` is
# used if found (it raises GitHub's 60-requests-an-hour anonymous limit), and one that's refused is
# dropped. COMPTON_RELEASES_REPO overrides the repo; the repo used is always printed.
#
# It doesn't check the release's signature: it comes from the same repo as the release, so a check
# here would prove nothing. Every later `<bin> update` checks it against the key built into the
# installed binary. This file is generated by the release pipeline; edits here are overwritten.
set -euo pipefail

# rust-release/build.sh bakes the app and repo into these defaults for the release's install.sh
# (only the repo for install-repo.sh), so keep each on one line with its marker.
PROJECT="${1:-}" # release-default: project
BIN="${2:-$PROJECT}" # release-default: bin
REPO="${COMPTON_RELEASES_REPO:-rcompton78/compton-releases}" # release-default: repo
if [[ -z "$PROJECT" ]]; then
  echo "Usage: $0 <project> [bin]" >&2
  exit 1
fi
if [[ ! "$REPO" =~ ^[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+$ ]]; then
  echo "Error: COMPTON_RELEASES_REPO must be <owner>/<name>, not '$REPO'." >&2
  exit 1
fi

API="${GITHUB_API_URL:-https://api.github.com}"
TARGET="x86_64-unknown-linux-musl"
# Keep in sync with publish.sh and compton-self-update's tag_prefix().
TAG_PREFIX="${PROJECT}@"
INSTALL_DIR="${INSTALL_DIR:-${HOME:?HOME is unset; set HOME or INSTALL_DIR}/.local/bin}"
DEST="$INSTALL_DIR/$BIN"
PER_PAGE=100
# The list is shared by every app (about one release a day), so an app untouched for roughly 10
# months falls past this cap and the install fails; accepted in COM-480's review.
MAX_PAGES=3

TOKEN_VAR="$(printf '%s' "$PROJECT" | tr '[:lower:]-' '[:upper:]_')_GH_TOKEN"
GH_TOKEN="${!TOKEN_VAR:-${GH_TOKEN:-${GITHUB_TOKEN:-}}}"
if [[ -z "$GH_TOKEN" ]] && command -v gh &> /dev/null; then
  GH_TOKEN=$(gh auth token 2> /dev/null || true)
fi
if [[ "$(uname -s)" != "Linux" || "$(uname -m)" != "x86_64" ]]; then
  echo "Error: releases are built for x86_64 Linux only; this is $(uname -s) $(uname -m)." >&2
  exit 1
fi
for cmd in curl python3 sha256sum tar; do
  if ! command -v "$cmd" &> /dev/null; then
    echo "Error: $cmd is required but wasn't found." >&2
    exit 1
  fi
done

WORK=$(mktemp -d)
STAGE=""
trap 'rm -rf "$WORK" ${STAGE:+"$STAGE"}' EXIT

# The auth header goes through a 0600 file, so the token never shows in curl's argv. Without a
# token the calls are anonymous.
AUTH_HEADER="$WORK/auth.header"
if [[ -n "$GH_TOKEN" ]]; then
  (umask 077 && printf 'Authorization: Bearer %s\n' "$GH_TOKEN" > "$AUTH_HEADER")
else
  : > "$AUTH_HEADER"
fi
api() {
  curl -fsSL -H "@${AUTH_HEADER}" "$@"
}

# Collects every listed page (up to the cap) into one JSON array file; the list is in creation
# order, not version order, so the newest build can be on any page.
TOKEN_DROPPED=false
echo "[]" > "$WORK/releases.json"
echo "Reading ${REPO}'s releases..."
for ((PAGE = 1; PAGE <= MAX_PAGES; PAGE++)); do
  # The status is read rather than failed on (-f), so a refused token is told apart from a
  # missing repo, the rate limit or a network failure (000).
  # A curl failure after the headers (a reset mid-body) still prints 200, so any non-zero exit
  # counts as a network failure.
  if ! STATUS=$(curl -sSL -H "@${AUTH_HEADER}" -H "Accept: application/vnd.github+json" \
    -o "$WORK/page.json" -w '%{http_code}' \
    "${API}/repos/${REPO}/releases?per_page=${PER_PAGE}&page=${PAGE}"); then
    STATUS=000
  fi
  if [[ "$STATUS" != 2* ]]; then
    if [[ "$STATUS" == 401 && -n "$GH_TOKEN" ]]; then
      # A stale or refused token shouldn't stop a public repo's install: carry on without it.
      echo "GitHub refused the token; trying without it." >&2
      GH_TOKEN=""
      TOKEN_DROPPED=true
      : > "$AUTH_HEADER"
      PAGE=$((PAGE - 1))
      continue
    fi
    echo "Error: couldn't list page ${PAGE} of ${REPO}'s releases (HTTP ${STATUS:-none})." >&2
    case "$STATUS" in
      403 | 429)
        echo "That's likely GitHub's rate limit (60 requests an hour per IP without a token);" >&2
        echo "try again later, or set $TOKEN_VAR (or GH_TOKEN/GITHUB_TOKEN) to raise it." >&2
        ;;
      404)
        if [[ -n "$GH_TOKEN" ]]; then
          echo "Check the repo name; if it's private, the token needs read access to it." >&2
        elif [[ "$TOKEN_DROPPED" == true ]]; then
          echo "Check the repo name; if it's private, your token (refused above) won't do." >&2
        else
          echo "Check the repo name; if it's private, it needs a token ($TOKEN_VAR, GH_TOKEN," >&2
          echo "GITHUB_TOKEN or 'gh auth login')." >&2
        fi
        ;;
      000 | "") echo "Couldn't reach ${API}; check the network." >&2 ;;
    esac
    exit 1
  fi
  COUNT=$(python3 -c '
import json, sys
page = json.load(open(sys.argv[1]))
merged = json.load(open(sys.argv[2])) + page
json.dump(merged, open(sys.argv[2], "w"))
print(len(page))
' "$WORK/page.json" "$WORK/releases.json")
  if [[ "$COUNT" -lt "$PER_PAGE" ]]; then
    break
  fi
done

# Prints the newest release's version, tarball URL, tarball name and checksum URL, one per line.
# Its rules match compton-self-update's pick_latest: a `<prefix><semver>` tag, both assets present,
# newest by (major, minor, patch); the patch is the UTC build stamp.
PICKED=$(python3 -c '
import json, re, sys
releases = json.load(open(sys.argv[1]))
prefix, bin_name, target = sys.argv[2], sys.argv[3], sys.argv[4]
semver = re.compile(r"^(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)(?:-[0-9A-Za-z.-]+)?(?:\+[0-9A-Za-z.-]+)?$")
best = None
for r in releases:
    if r.get("draft") or r.get("prerelease") or not r["tag_name"].startswith(prefix):
        continue
    version = r["tag_name"][len(prefix):]
    m = semver.match(version)
    if not m:
        continue
    core = tuple(int(g) for g in m.groups()[:3])
    asset = "{}-{}.{}.{}-{}.tar.gz".format(bin_name, *core, target)
    urls = {a["name"]: a["url"] for a in r.get("assets", [])}
    if asset in urls and asset + ".sha256" in urls and (best is None or core > best[0]):
        best = (core, version, urls[asset], asset, urls[asset + ".sha256"])
if best:
    print("\n".join(best[1:]))
' "$WORK/releases.json" "$TAG_PREFIX" "$BIN" "$TARGET")

if [[ -z "$PICKED" ]]; then
  echo "Error: no published ${TAG_PREFIX}* release of ${REPO} with a ${TARGET} tarball among the releases read (up to $((MAX_PAGES * PER_PAGE)))." >&2
  exit 1
fi
VERSION=$(sed -n 1p <<< "$PICKED")
TARBALL_URL=$(sed -n 2p <<< "$PICKED")
TARBALL=$(sed -n 3p <<< "$PICKED")
SUMS_URL=$(sed -n 4p <<< "$PICKED")

echo "Installing $BIN $VERSION to $INSTALL_DIR..."

# Download both to the temp dir and check the tarball before anything touches the install.
api -H "Accept: application/octet-stream" "$TARBALL_URL" -o "$WORK/$TARBALL"
api -H "Accept: application/octet-stream" "$SUMS_URL" -o "$WORK/$TARBALL.sha256"
(cd "$WORK" && sha256sum -c --status "$TARBALL.sha256") || {
  echo "Error: $TARBALL doesn't match its published sha256." >&2
  exit 1
}
mkdir -p "$WORK/extract"
tar -xzf "$WORK/$TARBALL" -C "$WORK/extract" "$BIN"
if ! REPORTED=$("$WORK/extract/$BIN" --version); then
  echo "Error: the downloaded $BIN failed to run its --version." >&2
  exit 1
fi
if [[ " $REPORTED " != *" $VERSION "* ]]; then
  echo "Error: the downloaded $BIN reports '$REPORTED', expected $VERSION." >&2
  exit 1
fi

# Copy beside the destination, then rename, so a running binary is never half-written. The
# staging file is a mktemp name: unique per run, so concurrent runs can't swap or delete each
# other's copies, and created O_EXCL, so a planted symlink is never followed.
mkdir -p "$INSTALL_DIR"
STAGE=$(mktemp "$DEST.download.XXXXXX")
cp "$WORK/extract/$BIN" "$STAGE"
chmod 755 "$STAGE"
mv -f "$STAGE" "$DEST"

echo "Installed $REPORTED."

case ":$PATH:" in
  *":$INSTALL_DIR:"*) ;;
  *)
    echo "Note: $INSTALL_DIR isn't on your PATH. Add this to your shell rc:"
    echo "  export PATH=\"$INSTALL_DIR:\$PATH\""
    ;;
esac
